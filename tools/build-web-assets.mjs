#!/usr/bin/env node
/**
 * Builds browser-facing assets for every course in resources/curricula/<id>/.
 * Each course keeps its source PDF, page PNG/WebP, audio and offline manifest
 * together so new grades never mix resources or offline-download sizes.
 *
 * Usage: node tools/build-web-assets.mjs [--quality 78] [--course <id>] [--force]
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const args=process.argv.slice(2);
const option=(name,fallback)=>{ const index=args.indexOf(name); return index===-1?fallback:args[index+1]; };
const quality=Number(option("--quality",78)), requestedCourse=option("--course",null), force=args.includes("--force");
if(!Number.isInteger(quality)||quality<1||quality>100) throw new Error("--quality must be an integer from 1 to 100");
const walk=(directory)=>existsSync(directory)?readdirSync(directory,{withFileTypes:true}).flatMap((entry)=>{ const path=join(directory,entry.name); return entry.isDirectory()?walk(path):[path]; }):[];
const include=(path)=>`./${relative(root,path).split("\\").join("/")}`;
const contentRoot=join(root,"content","curricula"), courseRoot=join(root,"resources","curricula"), iconsRoot=join(root,"resources","icons");
const courses=walk(contentRoot).filter((path)=>path.endsWith("manifest.json")).map((manifestPath)=>({ ...JSON.parse(readFileSync(manifestPath,"utf8")), contentRoot:dirname(manifestPath) }));
const selected=courses.filter((course)=>!requestedCourse||course.id===requestedCourse);
if(!selected.length) throw new Error(requestedCourse?`Unknown course: ${requestedCourse}`:"No course manifests found");

let created=0, skipped=0;
for(const course of selected) {
  const pages=join(courseRoot,course.id,"pages");
  for(const source of walk(pages).filter((path)=>path.toLowerCase().endsWith(".png"))) {
    const output=source.replace(/\.png$/i,".webp");
    // Rebuild when the original page was changed after its WebP sibling. This
    // catches revised textbook images without requiring an easy-to-forget flag.
    if(existsSync(output)&&!force&&statSync(output).mtimeMs>=statSync(source).mtimeMs) { skipped+=1; continue; }
    mkdirSync(dirname(output),{recursive:true});
    execFileSync("cwebp",["-quiet","-q",String(quality),"-m","6",source,"-o",output],{stdio:"inherit"});
    created+=1;
  }
}

const commonAssets=["./","./index.html","./style.css","./main.js","./sw.js","./manifest.webmanifest"];
for(const course of selected) {
  const resourceRoot=join(courseRoot,course.id), pages=join(resourceRoot,"pages"), audio=join(resourceRoot,"audio"), offline=join(resourceRoot,"offline-assets.js");
  const assets=[...commonAssets,include(offline)];
  for(const directory of [course.contentRoot,audio,pages,iconsRoot]) for(const file of walk(directory)) {
    if(file.endsWith(".png")&&file.startsWith(pages)) continue;
    if(/\.(?:js|webp|m4a|png)$/i.test(file)) assets.push(include(file));
  }
  const unique=[...new Set(assets)].sort();
  const totalBytes=unique.reduce((total,asset)=>{ const file=join(root,asset.slice(2)); return total+(existsSync(file)&&statSync(file).isFile()?statSync(file).size:0); },0);
  // Hash actual publishable bytes, not just paths or sizes: a same-size audio
  // replacement or revised WebP must still offer an offline refresh. Exclude
  // the generated manifest itself to avoid a self-referential hash cycle.
  const version=createHash("sha256").update(unique.filter((asset)=>asset!==include(offline)).map((asset)=>{ const file=join(root,asset.slice(2)); return `${asset}:${existsSync(file)&&statSync(file).isFile()?createHash("sha256").update(readFileSync(file)).digest("hex"):"missing"}`; }).join("\n")).digest("hex").slice(0,12);
  writeFileSync(offline,`// Generated by tools/build-web-assets.mjs\nwindow.ENGLISH_OFFLINE_COURSE_ID=${JSON.stringify(course.id)};\nwindow.ENGLISH_OFFLINE_ASSET_VERSION=${JSON.stringify(version)};\nwindow.ENGLISH_OFFLINE_ASSET_BYTES=${totalBytes};\nwindow.ENGLISH_OFFLINE_ASSETS=${JSON.stringify(unique)};\n`,"utf8");
  console.log(`${course.id}: offline bundle ${unique.length} files, ${(totalBytes/1024/1024).toFixed(1)} MB.`);
}
console.log(`WebP build complete: ${created} created, ${skipped} already present.`);
