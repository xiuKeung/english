#!/usr/bin/env node
/**
 * Builds browser-facing textbook assets for every grade/semester in this repo.
 * Source PNGs stay local for future OCR/hotspot work; the site loads WebP.
 *
 * Usage: node tools/build-web-assets.mjs [--quality 78] [--force]
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const quality=Number(process.argv[process.argv.indexOf("--quality")+1]||78);
const force=process.argv.includes("--force");
if(!Number.isInteger(quality)||quality<1||quality>100) throw new Error("--quality must be an integer from 1 to 100");
const walk=(directory)=>readdirSync(directory,{withFileTypes:true}).flatMap((entry)=>{ const path=join(directory,entry.name); return entry.isDirectory()?walk(path):[path]; });
const pageRoot=join(root,"resources","pages"), pngs=walk(pageRoot).filter((path)=>path.toLowerCase().endsWith(".png"));
let created=0, skipped=0;
for(const source of pngs) {
  const output=source.replace(/\.png$/i,".webp");
  if(existsSync(output)&&!force) { skipped+=1; continue; }
  mkdirSync(dirname(output),{recursive:true});
  execFileSync("cwebp",["-quiet","-q",String(quality),"-m","6",source,"-o",output],{stdio:"inherit"});
  created+=1;
}
const include=(path)=>`./${relative(root,path).split("\\").join("/")}`;
const assetRoots=[join(root,"content"),join(root,"resources","audio"),pageRoot,join(root,"resources","icons")];
const assets=["./","./index.html","./style.css","./main.js","./sw.js","./manifest.webmanifest","./resources/offline-assets.js"];
for(const directory of assetRoots) for(const file of walk(directory)) {
  if(file.endsWith(".png")&&file.startsWith(pageRoot)) continue;
  if(/\.(?:js|webp|m4a|png)$/i.test(file)) assets.push(include(file));
}
const unique=[...new Set(assets)].sort();
const totalBytes=unique.reduce((total,asset)=>{ const file=join(root,asset.slice(2)); return total+(existsSync(file)&&statSync(file).isFile()?statSync(file).size:0); },0);
const version=createHash("sha256").update(unique.map((asset)=>{ const file=join(root,asset.slice(2)); return `${asset}:${existsSync(file)?statSync(file).size:0}`; }).join("\n")).digest("hex").slice(0,12);
writeFileSync(join(root,"resources","offline-assets.js"),`// Generated by tools/build-web-assets.mjs\nwindow.ENGLISH_OFFLINE_ASSET_VERSION=${JSON.stringify(version)};\nwindow.ENGLISH_OFFLINE_ASSET_BYTES=${totalBytes};\nwindow.ENGLISH_OFFLINE_ASSETS=${JSON.stringify(unique)};\n`,`utf8`);
console.log(`WebP build complete: ${created} created, ${skipped} already present. Offline bundle: ${unique.length} files, ${(totalBytes/1024/1024).toFixed(1)} MB.`);
